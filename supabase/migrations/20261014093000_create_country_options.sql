-- These are UI labels/options, not determinations of sovereignty, legal status, or work eligibility.
-- This table contains no city/town records and makes no claims about administrative parent paths.

BEGIN;

CREATE TABLE public.country_options (
  code text PRIMARY KEY
    CONSTRAINT country_options_code_format CHECK (code ~ '^[A-Z]{2}$'),
  name text NOT NULL
    CONSTRAINT country_options_name_nonempty CHECK (length(btrim(name)) > 0)
);

COMMENT ON TABLE public.country_options IS
  'User-facing country/area dropdown labels from umpirsky/country-list at commit bd490a163ae4709bbe4b54c4f638f24e032828d2 (MIT). Labels do not assert sovereignty, legal status, or work eligibility. City/town data is maintained separately.';

ALTER TABLE public.country_options ENABLE ROW LEVEL SECURITY;

-- Public users may read the dropdown, but cannot alter the reference data from the browser.
REVOKE ALL ON TABLE public.country_options FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.country_options TO anon, authenticated;

CREATE POLICY country_options_public_read
  ON public.country_options
  FOR SELECT
  TO anon, authenticated
  USING (true);

